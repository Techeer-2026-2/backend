CREATE TABLE public.music_playlists (
    playlist_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id bigint NOT NULL REFERENCES public.music_users(user_id),
    title varchar(100) NOT NULL,
    description varchar(500),
    share_code varchar(36) UNIQUE,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    deleted_at timestamp
);
CREATE INDEX music_playlists_owner_idx ON public.music_playlists(owner_user_id);

CREATE TABLE public.music_playlist_tracks (
    playlist_id bigint NOT NULL REFERENCES public.music_playlists(playlist_id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position >= 0),
    track_id varchar(128) NOT NULL REFERENCES ranking.track(track_id),
    PRIMARY KEY (playlist_id, position),
    UNIQUE (playlist_id, track_id)
);

-- 사용자당 현재 재생 중인 플레이리스트 한 개만 유지한다.
CREATE TABLE public.music_active_listening (
    user_id bigint PRIMARY KEY REFERENCES public.music_users(user_id) ON DELETE CASCADE,
    playlist_id bigint NOT NULL REFERENCES public.music_playlists(playlist_id) ON DELETE CASCADE,
    h3_cell varchar(15) NOT NULL,
    location_recorded_at timestamptz NOT NULL,
    heartbeat_at timestamptz NOT NULL
);
CREATE INDEX music_active_listening_count_idx
    ON public.music_active_listening(playlist_id, h3_cell, heartbeat_at, location_recorded_at);
